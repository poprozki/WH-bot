export async function buildVolatileBlock(client) {
  const settings = await one(`SELECT * FROM settings WHERE id`);
  const now = new Date();

  const today = now.toLocaleDateString('ru-RU', {
    weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: cfg.tz,
  });
  const time = now.toLocaleTimeString('ru-RU', {
    hour: '2-digit', minute: '2-digit', timeZone: cfg.tz,
  });
  const isoDate = new Intl.DateTimeFormat('en-CA', { timeZone: cfg.tz }).format(now);

  const masters = await q(`SELECT name FROM masters WHERE active ORDER BY id`);

  const parts = [
    `Сегодня: ${today}, сейчас ${time}. Дата в формате для инструментов: ${isoDate}.`,
    `Тебя зовут ${settings.bot_name || 'Алина'}. Это ТВОЁ имя, не имя клиентки.`,
    `Студия: ${settings.salon_name}${settings.address ? `, ${settings.address}` : ''}.`,
    `Мастера: ${masters.map((m) => m.name).join(', ')}.`,
    `Записаться можно не раньше чем через ${settings.min_lead_minutes} минут от текущего момента и не дальше чем на ${settings.booking_horizon_days} дней вперёд.`,
  ];

  if (client) {
    if (client.name) parts.push(`Клиентку зовут ${client.name}.`);
    if (client.visits_count > 0) {
      parts.push(`Она уже была у нас ${client.visits_count} раз(а). Это постоянная клиентка, поздоровайся как со знакомой.`);
    } else {
      parts.push(`Она пишет впервые.`);
    }
    if (client.last_visit_at) {
      const last = new Date(client.last_visit_at).toLocaleDateString('ru-RU', {
        day: 'numeric', month: 'long', timeZone: cfg.tz,
      });
      parts.push(`Последний визит: ${last}.`);
    }
    if (client.usual_service_name) {
      parts.push(`Обычно делает: ${client.usual_service_name}. Если скажет «как обычно» — это оно, но обязательно подтверди словами, прежде чем записывать.`);
    }
    if (client.preferred_master_name) {
      parts.push(`Обычно ходит к мастеру: ${client.preferred_master_name}.`);
    }
  }

  if (settings.extra_rules && settings.extra_rules.trim()) {
    parts.push(
      `\nПРАВИЛА ЭТОЙ СТУДИИ (от владелицы, отвечай по ним как по своим знаниям):\n${settings.extra_rules.trim()}`
    );
  }
  if (settings.price_policy_text) {
    parts.push(`Если просят скидку — отвечай по смыслу так: «${settings.price_policy_text}»`);
  }
  if (settings.payment_note) {
    parts.push(`Про оплату: ${settings.payment_note}`);
  }
  if (settings.owner_name) {
    parts.push(
      `Живого администратора зовут ${settings.owner_name}. Обещая, что человек ответит, ` +
      'называй её по имени — это звучит человечнее, чем «администратор».'
    );
  }

  return parts.join('\n');
}
