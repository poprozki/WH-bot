const RESCHED_RE = new RegExp(
  '(?:перенес|перенёс|перенос|подвинь|сдвин|поменя(?:ть|йте)\\s+(?:время|день|дату)|' +
  'на\\s+(?:час|полчас|полтора|\\d+)[а-яё]*\\s*(?:позже|раньше|попозже|пораньше)|' +
  '(?:по)?позже|(?:по)?раньше|в другое время|на другой день|' +
  'не успеваю к|можно (?:ли )?(?:в|на) друг)',
  'i'
);

const ADD_RE = new RegExp(
  '(?:добав|ещё\\s+(?:и\\s+)?(?:педикюр|маникюр|дизайн|снятие|покрытие|френч)|' +
  'вместе с|заодно|плюс\\s+(?:педикюр|дизайн|снятие)|' +
  'можно\\s+(?:ещё|еще)\\s|и\\s+(?:педикюр|дизайн)\\s+тоже)',
  'i'
);

const NEW_RE = new RegExp(
  '(?:ещё\\s+раз|еще\\s+раз|на\\s+другой\\s+день\\s+тоже|второй\\s+раз|' +
  'на\\s+следующ(?:ий|ей)\\s+(?:месяц|неделе)|через\\s+(?:месяц|три недели|две недели))',
  'i'
);

const LATE_RE = new RegExp(
  '(?:опозда|задержив|застрял|в пробк|буду позже минут|подъеду позже|' +
  'немного задерж)',
  'i'
);

const CANCEL_RE = new RegExp(
  '(?:отмен|не смогу(?:\\s+прийти)?|не получится|не приду|отказ(?:ываюсь|аться)|' +
  'снимите запись|уберите запись)',
  'i'
);

export function routeBookingIntent(text, active = []) {
  const t = String(text || '');
  const has = active.length > 0;

  if (CANCEL_RE.test(t)) {
    return has
      ? { op: 'CANCEL', hint:
          'Клиентка отменяет. Отмену принимаем ВСЕГДА, без причины и без условий — ' +
          'причину не спрашивай. Один закрытый вопрос с датой и временем из её записи, ' +
          'потом cancel_booking. Ни слова про штрафы и опоздания.' }
      : { op: 'NONE', hint: 'Активных записей нет — уточни, что именно она хочет отменить.' };
  }

  if (LATE_RE.test(t)) {
    return has
      ? { op: 'LATE', hint:
          'Клиентка опаздывает — это НЕ перенос. Время записи НЕ МЕНЯЙ и никаких ' +
          'инструментов не вызывай. Просто спокойно ответь, что предупредишь мастера, ' +
          'и позови человека через escalate_to_human — решать, ждать или двигать, ' +
          'должен живой администратор.' }
      : { op: 'NONE', hint: '' };
  }

  if (has && RESCHED_RE.test(t)) {
    return { op: 'RESCHEDULE', hint:
      `У неё УЖЕ ЕСТЬ запись (номер ${active[0].id}). Она хочет ПЕРЕНЕСТИ именно её, ` +
      'а не записаться заново. Найди новое время через find_slots и вызови ' +
      'reschedule_booking с этим номером. НЕ вызывай create_booking — иначе в ' +
      'расписании окажутся две записи вместо одной.' };
  }

  if (has && ADD_RE.test(t) && !NEW_RE.test(t)) {
    return { op: 'ADD_SERVICE', hint:
      `У неё есть запись номер ${active[0].id}. Она хочет ДОБАВИТЬ услугу к тому же ` +
      'визиту — вызови add_service. Отдельную запись НЕ создавай: клиентка придёт ' +
      'один раз, а в расписании оказались бы две строки. Поместится ли удлинившийся ' +
      'визит, проверит сама система: если нет, она вернёт причину, и ты предложишь ' +
      'перенос или отдельный день.' };
  }

  if (has && NEW_RE.test(t)) {
    return { op: 'NEW', hint:
      'У неё уже есть будущая запись, но она хочет записаться ЕЩЁ РАЗ на другой день. ' +
      'Это нормально: создавай новую через create_booking.' };
  }

  if (has) {

    return { op: 'UNKNOWN_WITH_BOOKING', hint:
      'У неё есть действующая запись, детали уже перед тобой выше. ' +
      'Если она спрашивает время, мастера или цену — отвечай сразу, ничего не переспрашивая ' +
      'и не вызывая инструментов.' };
  }

  return { op: 'NONE', hint: '' };
}
